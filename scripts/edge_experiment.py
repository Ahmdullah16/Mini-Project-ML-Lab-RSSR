"""MP18: learn a known Sobel operator; imitation is not edge-ground-truth accuracy."""
import json
from pathlib import Path
import numpy as np
import torch
from torch.nn import functional as F
import rasterio
import matplotlib
matplotlib.use('Agg')
import matplotlib.pyplot as plt
from rssr.core import digest

root=Path(__file__).resolve().parents[1]
torch.set_num_threads(2); torch.manual_seed(18)
torch.use_deterministic_algorithms(True)
sobel=torch.tensor([[[-1.,0,1],[-2,0,2],[-1,0,1]],
                    [[-1.,-2,-1],[0,0,0],[1,2,1]]])[:,None]/8
generator=torch.Generator().manual_seed(18)
# White-noise fixtures excite all kernel coefficients; separate edge patterns validate.
training=torch.rand((32,1,16,16),generator=generator)
targets=F.conv2d(F.pad(training,(1,1,1,1),mode='replicate'),sobel)
model=torch.nn.Conv2d(1,2,3,bias=False)
optimizer=torch.optim.Adam(model.parameters(),lr=.03)
history=[]
for step in range(500):
    model.train(); optimizer.zero_grad()
    output=model(F.pad(training,(1,1,1,1),mode='replicate'))
    loss=F.mse_loss(output,targets); loss.backward(); optimizer.step()
    if step in (0,99,499): history.append({'step':step+1,'mse':loss.item()})
model.eval()
patterns=torch.zeros((3,1,16,16))
patterns[0,:,:,8:]=1; patterns[1,:,8:,:]=1
patterns[2,0]=torch.eye(16)
with torch.inference_mode():
    reference=F.conv2d(F.pad(patterns,(1,1,1,1),mode='replicate'),sobel)
    prediction=model(F.pad(patterns,(1,1,1,1),mode='replicate'))
    validation=float(F.mse_loss(prediction,reference))
    error=float((model.weight-sobel).abs().max())
    constant=torch.ones((1,1,8,8))
    padded=F.conv2d(constant,sobel,padding=1)
    replicated=F.conv2d(F.pad(constant,(1,1,1,1),mode='replicate'),sobel)
assert validation<1e-10 and error<1e-4
assert torch.count_nonzero(replicated)==0 and padded.abs().max()>0
assert torch.all(reference[0,1]==0) and torch.all(reference[1,0]==0)

manifest=json.loads((root/'configs/naip-pilot-manifest.json').read_text())
scene=next(s for s in manifest['scenes'] if s['split']=='train')
source=root/'data'/scene['path']; assert digest(source)==scene['sha256']
with rasterio.open(source) as ds:
    window=rasterio.windows.Window(0,0,64,64)
    image=ds.read(1,window=window).astype(np.float32)/manifest['divisor']
    assert (ds.read_masks(1,window=window)>0).all()
with torch.inference_mode():
    real=F.pad(torch.from_numpy(image)[None,None],(1,1,1,1),mode='replicate')
    fixed=F.conv2d(real,sobel)[0]; learned=model(real)[0]
    magnitude=torch.linalg.vector_norm(fixed,dim=0).numpy()
    learned_magnitude=torch.linalg.vector_norm(learned,dim=0).numpy()
    real_mse=float(F.mse_loss(learned,fixed))
fig,axes=plt.subplots(2,4,figsize=(12,6),layout='constrained')
for ax,array,title in zip(axes[0],[sobel[0,0],model.weight[0,0].detach(),sobel[1,0],model.weight[1,0].detach()],['Fixed Gx','Learned Gx','Fixed Gy','Learned Gy']):
    ax.imshow(array,cmap='coolwarm',vmin=-.25,vmax=.25); ax.set_title(title)
for ax,array,title in zip(axes[1],[image,magnitude,learned_magnitude,padded[0].square().sum(0).sqrt().numpy()],['NAIP red input','Fixed magnitude','Learned magnitude','Zero-boundary false edges']):
    ax.imshow(array,cmap='gray',vmin=0,vmax=float(magnitude.max()) if 'magnitude' in title else float(np.max(array)))
    ax.set_title(title)
fig.savefig(root/'reports/mp18-edges.png',dpi=120); plt.close(fig)
report={'task':'Supervised imitation of normalized Sobel, not independent edge detection truth',
        'seed':18,'device':'cpu','torch':torch.__version__,'optimizer':'Adam','lr':.03,
        'steps':500,'batch_size':32,'training':'32 seeded uniform-noise 16x16 fixtures',
        'validation':'vertical step, horizontal step, diagonal line; disjoint from noise fixtures',
        'history':history,'validation_component_mse':validation,'max_kernel_error':error,
        'replicate_constant_max':float(replicated.abs().max()),'zero_constant_max':float(padded.abs().max()),
        'real_component_mse_vs_sobel':real_mse,'real_source':scene,'window':[0,0,64,64],
        'license':'NAIP public domain; USDA/OpenSR attribution','scaling':'stored red DN/10000, not calibrated reflectance',
        'limitations':'Labels are generated by Sobel. Low error proves imitation only, not superiority or semantic boundary accuracy. No new downloads or held-out evaluation.'}
(root/'reports/mp18-edges.json').write_text(json.dumps(report,indent=2)+'\n')
print(json.dumps(report,indent=2))
